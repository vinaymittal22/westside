/* ── Helpers ──────────────────────────────────────────────────────── */
export const getFeaturedProducts   = () => products.slice(0, 8);
export const getProductsByOccasion = (o: string) =>
  o === "all" ? products : products.filter((p) => p.occasion === o);
export const getProductsByCategory = (c: string) =>
  c === "all" ? products : products.filter((p) => p.category === c);
export const getProductsByGender   = (g: string) =>
  g === "all" ? products : products.filter((p) => p.gender === g);
export const getProductsByTags     = (tags: string[]) => {
  const lower = tags.map((t) => t.toLowerCase());
  return products
    .map((p) => ({
      p,
      score: [...(p.tags ?? []), p.occasion, p.category]
        .filter((t) => lower.includes(t.toLowerCase())).length,
    }))
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((x) => x.p)
    .slice(0, 6);
};
